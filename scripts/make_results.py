"""Write docs/RESULTS.md and docs/reports/ from the JSON that reproduce.py produced.

    python scripts/make_results.py --out out
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def fmt(x, digits=4):
    if x is None:
        return "n/a"
    if isinstance(x, float):
        return f"{x:.{digits}g}"
    return str(x)


def campaign_table(c: dict) -> list[str]:
    rows = [
        "| Test case | Verdict | Runs | Failing runs | Errors | Worst margin | Point with the worst margin | Wall time |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for ref, o in sorted(c["outcomes"].items()):
        pt = o.get("worst_assignment") or {}
        shown = ", ".join(f"{k}={v:.3g}" for k, v in sorted(pt.items()))
        rows.append(
            f"| {ref} | **{o['verdict'].upper()}** | {o['n_executed']} | {o.get('n_fail', 'n/a')} "
            f"| {o.get('n_errors', 0)} | {fmt(o['worst_robustness'])} | {shown} "
            f"| {o.get('wall_time_s', 0):.1f} s |"
        )
    return rows


def gate_table(g: dict) -> list[str]:
    order = {"blocker": 0, "major": 1, "minor": 2, "info": 3}
    rows = ["| Severity | Rule | Subject |", "|---|---|---|"]
    for f in sorted(g["findings"], key=lambda f: (order[f["severity"]], f["rule"], f["subject"])):
        rows.append(f"| {f['severity']} | {f['rule']} | {f['subject']} |")
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=REPO / "out")
    args = ap.parse_args()
    out = args.out
    docs = REPO / "docs"
    (docs / "reports").mkdir(parents=True, exist_ok=True)
    bench = load(out / "bench.json") or {}

    L = [
        "# Results",
        "",
        "Generated by `scripts/make_results.py` from the JSON written by `scripts/reproduce.py`.",
        "Do not edit by hand; re-run `python scripts/reproduce.py --osc` instead.",
        "",
        "The T200 truck, its hazards, architectures and parameter sets are fictional example",
        "data. The numbers below are what SafeGate computed for that data on the machine",
        "named at the end; they are not measurements of any real vehicle.",
        "",
    ]
    titles = {
        "revA": "T200 rev A (baseline, as first designed)",
        "revB": "T200 rev B (after the rev A findings were addressed)",
    }
    for name in ("revA", "revB"):
        c = load(out / name / "campaign.json")
        g = load(out / name / "gate.json")
        s = load(out / name / "summary.json")
        if not (c and g and s):
            continue
        n_runs = sum(o["n_executed"] for o in c["outcomes"].values())
        blockers = sum(1 for f in g["findings"] if f["severity"] == "blocker")
        L += [
            f"## {titles[name]}",
            "",
            f"SIL runner, {n_runs} runs, {s['workers']} worker processes, campaign wall time "
            f"{c['wall_time_s']:.1f} s. Gate exit {s['gate_exit']} "
            f"({'pass' if g['passed'] else 'fail'}, {len(g['findings'])} findings, {blockers} blockers). "
            f"`safegate verify` with the pinned key, the anchor and the report: exit {s['verify_exit']}.",
            "",
            *campaign_table(c),
            "",
            "Worst margin is the minimum STL robustness in the criterion's unit (m, s or m/s); "
            "negative means the requirement was violated by that much.",
            "",
            "Gate findings:",
            "",
            *gate_table(g),
            "",
            f"Full report: [docs/reports/T200-{name}-V-and-V.md](reports/T200-{name}-V-and-V.md)",
            "",
        ]
        shutil.copyfile(out / name / "V-and-V.md", docs / "reports" / f"T200-{name}-V-and-V.md")

    x = load(out / "cross_runner.json")
    s_osc = load(out / "revB-scenario_execution" / "summary.json")
    c_osc = load(out / "revB-scenario_execution" / "campaign.json")
    if x and s_osc and c_osc:
        L += [
            "## Same campaign through Intel Labs scenario_execution",
            "",
            "Rev B was run a second time with `--runner scenario_execution`: every concrete run is an",
            "OpenSCENARIO 2 file parsed and executed by `scenario_execution` 1.5.0 in step-based",
            "simulation mode, with the SafeGate SIL world behind its `SimulationInterface`.",
            "",
            "| | |",
            "|---|---|",
            f"| Runs, in-process SIL runner | {x['runs_sil']} |",
            f"| Runs, scenario_execution runner | {x['runs_osc']} |",
            f"| Same test case, assignment and seed in both | {x['matched_points']} |",
            f"| Same verdict | {x['same_verdict']} |",
            f"| Bit-identical robustness | {x['bit_identical_robustness']} |",
            f"| Largest robustness difference | {x['max_abs_robustness_diff']:.3g} |",
            f"| Campaign wall time (scenario_execution, {s_osc['workers']} workers) | {c_osc['wall_time_s']:.0f} s |",
            "",
            "The wall time is dominated by `scenario_execution` parsing the OSC2 files for every",
            "run (about 1.8 s of about 2 s per run, measured); running it in-process instead of one",
            "process per run is no faster. The falsification phase is sequential by design.",
            "",
        ]

    o = load(out / "s3.json")
    if o:
        L += [
            "## Evidence in object storage",
            "",
            "Rev A was run again with `--store s3://...` against a local MinIO server, which",
            "honours S3 conditional writes: every manifest entry is its own object, created",
            "with `If-None-Match: *`.",
            "",
            "| | |",
            "|---|---|",
            f"| Manifest entries (objects) | {o['entries']} |",
            f"| Outcomes identical to the filesystem campaign | {o['outcomes_identical_to_filesystem']} |",
            f"| `safegate run` wall time (CLI, 16 workers) | {o['run_cli_s']:.1f} s |",
            f"| `safegate verify` with pinned key, anchor and report | exit {o['verify_exit']}, {o['verify_cli_s']:.1f} s |",
            "",
        ]

    r2 = load(out / "ros2.json")
    if r2:
        L += [
            "## Through ROS 2",
            "",
            "Rev B TC-CROSS-001 with `--runner ros2`: every run starts a ROS 2 Jazzy container in",
            "which the SafeGate plant node publishes the world as `sensor_msgs/JointState` while",
            "`ros2 bag record` writes MCAP; the bag is extracted on the host with the",
            "topic-to-signal mapping. The runner is declared non-deterministic, so each point ran",
            "three times.",
            "",
            "| | |",
            "|---|---|",
            f"| Points | {r2['points']} |",
            f"| ROS 2 executions (3 per point) | {r2['ros2_executions']} |",
            f"| Executions with verdict and robustness identical to SIL | {r2['executions_identical_to_sil']} |",
            f"| Test-case verdict through ROS 2 | {r2['ros2_verdict']} |",
            f"| Wall time, ros2 runner (8 containers in parallel) | {r2['ros2_wall_s']:.0f} s |",
            f"| Wall time, SIL runner, same points | {r2['sil_wall_s']:.1f} s |",
            "",
            "The first attempt came back FLAKY: parallel containers on Docker's default bridge",
            "network discovered each other over DDS multicast, and recorders captured other runs.",
            "Containers now run with `--network none` and localhost-only ROS 2 discovery.",
            "",
        ]

    t = load(out / "tamper.json")
    if t:
        r = t["rewrite_and_resign"]
        L += [
            "## Tamper evidence, demonstrated on the rev A store",
            "",
            f"The rev A store holds {t['entries']} manifest entries, {t['failing_runs']} of them failing runs.",
            "",
            "| Manipulation | `safegate verify` | Detail |",
            "|---|---|---|",
            f"| Delete the {t['failing_runs']} failing-run entries | exit {t['delete_failing_runs']['exit']} | "
            f"{t['delete_failing_runs']['problems']} problems, first: `{(t['delete_failing_runs']['first'] or [''])[0]}` |",
            f"| Flip one failing verdict to pass | exit {t['flip_one_verdict']['exit']} | "
            f"first: `{(t['flip_one_verdict']['first'] or [''])[0]}` |",
            f"| Rewrite the chain without failing runs, re-sign with a new key, no trusted key given | "
            f"exit {r['verify_without_trusted_key_exit']} | a self-consistent forgery passes plain chain checks |",
            f"| Same forgery, verified with the pinned key | exit {r['verify_with_trusted_key_exit']} | "
            f"{r['trusted_key_problems']} entries signed by an untrusted key |",
            f"| Same forgery, verified against the published anchor | exit {r['verify_with_anchor_exit']} | "
            f"`{(r['anchor_first'] or [''])[0]}` |",
            f"| Edit the issued report (NON-CONFORMING to CONFORMING) | exit {t['edit_report']['exit']} | "
            f"`{(t['edit_report']['first'] or [''])[0]}` |",
            "",
            "The third row is why policy `trusted_signers` and anchors exist: chaining and",
            "signatures verified against a key stored in the same place prove nothing against",
            "someone who can write that place. SafeGate 0.3.0 had exactly that weakness.",
            "",
        ]

    if bench:
        L += [
            "## Micro-benchmarks",
            "",
            f"Single thread, {bench.get('cpu')}, Python {bench.get('python')}. Best of 5 (Until: best of 3).",
            "",
            "| Measurement | Value |",
            "|---|---|",
        ]
        for k, v in bench.items():
            if k in ("cpu", "python", "single_thread"):
                continue
            L.append(f"| {k} | {fmt(v)} |")
        L += [
            "",
            "Unbounded `always`/`eventually` is vectorised; bounded windows use the O(n)",
            "monotonic-wedge loop in pure Python (about 1 microsecond per sample); `Until` is O(n^2).",
            "",
        ]

    text = "\n".join(L) + "\n"
    assert chr(0x2014) not in text and chr(0x2013) not in text  # no long dashes in docs
    (docs / "RESULTS.md").write_text(text)
    print(f"wrote {docs / 'RESULTS.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
